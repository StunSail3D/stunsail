#!/usr/bin/env python3
"""Minimal ASGI reverse proxy: the TLS frontend for the loopback-only StunSail Core.

Experimental. Served by the already-locked uvicorn with --ssl-certfile/--ssl-keyfile
and forwards to Core with the already-locked httpx, so it adds no runtime dependency.
Core stays bound to 127.0.0.1:8000; this frontend is the only LAN-facing listener
(8443). Moonraker is never proxied.
"""

from __future__ import annotations

from collections.abc import AsyncIterator, Awaitable, Callable, MutableMapping
from typing import Any

import httpx

CORE_BASE_URL = "http://127.0.0.1:8000"
REQUEST_TIMEOUT = httpx.Timeout(30.0, connect=10.0)
HOP_BY_HOP = frozenset(
    {
        "connection",
        "keep-alive",
        "proxy-authenticate",
        "proxy-authorization",
        "te",
        "trailers",
        "transfer-encoding",
        "upgrade",
    }
)
# content-length is regenerated by httpx for the streamed request body; the
# forwarded-* headers are rewritten here because this frontend is the TLS edge.
STRIPPED_REQUEST_HEADERS = HOP_BY_HOP | {
    "host",
    "content-length",
    "x-forwarded-for",
    "x-forwarded-proto",
}

Scope = MutableMapping[str, Any]
Receive = Callable[[], Awaitable[MutableMapping[str, Any]]]
Send = Callable[[MutableMapping[str, Any]], Awaitable[None]]


async def _lifespan(receive: Receive, send: Send) -> None:
    while True:
        message = await receive()
        if message["type"] == "lifespan.startup":
            await send({"type": "lifespan.startup.complete"})
        elif message["type"] == "lifespan.shutdown":
            await send({"type": "lifespan.shutdown.complete"})
            return


def _forward_headers(scope: Scope) -> list[tuple[str, str]]:
    pairs = [
        (name.decode("latin-1").lower(), value.decode("latin-1"))
        for name, value in scope["headers"]
    ]
    forwarded = [(name, value) for name, value in pairs if name not in STRIPPED_REQUEST_HEADERS]
    prior = ", ".join(value for name, value in pairs if name == "x-forwarded-for")
    client = scope.get("client")
    if client and client[0]:
        prior = f"{prior}, {client[0]}" if prior else client[0]
    if prior:
        forwarded.append(("x-forwarded-for", prior))
    forwarded.append(("x-forwarded-proto", "https"))
    return forwarded


async def _request_body(receive: Receive) -> AsyncIterator[bytes]:
    while True:
        message = await receive()
        if message["type"] == "http.disconnect":
            return
        body = message.get("body", b"")
        if body:
            yield body
        if not message.get("more_body", False):
            return


async def _send_error(send: Send, status: int, text: str) -> None:
    body = text.encode("utf-8")
    await send(
        {
            "type": "http.response.start",
            "status": status,
            "headers": [
                (b"content-type", b"text/plain; charset=utf-8"),
                (b"content-length", str(len(body)).encode("ascii")),
            ],
        }
    )
    await send({"type": "http.response.body", "body": body})


async def _send_response(send: Send, response: httpx.Response) -> None:
    headers = [
        (name.lower().encode("latin-1"), value.encode("latin-1"))
        for name, value in response.headers.multi_items()
        if name.lower() not in HOP_BY_HOP
    ]
    await send({"type": "http.response.start", "status": response.status_code, "headers": headers})
    async for chunk in response.aiter_raw():
        await send({"type": "http.response.body", "body": chunk, "more_body": True})
    await send({"type": "http.response.body", "body": b"", "more_body": False})


async def _proxy(scope: Scope, receive: Receive, send: Send) -> None:
    query = scope["query_string"].decode("latin-1")
    target = scope["path"] + (f"?{query}" if query else "")
    headers = _forward_headers(scope)
    async with httpx.AsyncClient(base_url=CORE_BASE_URL, timeout=REQUEST_TIMEOUT) as client:
        request = client.build_request(
            scope["method"], target, headers=headers, content=_request_body(receive)
        )
        try:
            response = await client.send(request, stream=True)
        except (httpx.ConnectError, httpx.ConnectTimeout):
            await _send_error(send, 502, "StunSail Core upstream is unreachable")
            return
        try:
            await _send_response(send, response)
        finally:
            await response.aclose()


async def app(scope: Scope, receive: Receive, send: Send) -> None:
    if scope["type"] == "lifespan":
        await _lifespan(receive, send)
    elif scope["type"] == "http":
        await _proxy(scope, receive, send)
    elif scope["type"] == "websocket":
        await send({"type": "websocket.close", "code": 1008})
